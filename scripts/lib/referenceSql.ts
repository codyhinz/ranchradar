/**
 * Turns the generated reference data (forms, names, items, variants, regulations) into one SQL
 * migration that brings Supabase in line with data/. Every statement is an upsert, so applying it
 * over older data changes only what's different, and running it twice does nothing. Reference rows
 * are never deleted (stable IDs: rosters keep pointing at retired forms); only each regulation's
 * legal lists are trimmed to match its file.
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { FormRecord, ItemRecord, NameMap, RegulationFile, VariantRecords } from './data';

export const MIGRATIONS_DIR = join(import.meta.dirname, '..', '..', 'supabase', 'migrations');
const SUFFIX = '_reference_data.sql';

export interface ReferenceData {
  regulations: RegulationFile[];
  forms: FormRecord[];
  formNames: NameMap;
  items: ItemRecord[];
  itemNames: NameMap;
  variants: VariantRecords;
}

/** A SQL string literal; doubling quotes is the whole escape for standard strings. */
export function lit(value: string | number | null): string {
  if (value === null) return 'null';
  if (typeof value === 'number') return String(value);
  return `'${value.replaceAll("'", "''")}'`;
}

const byId = <T extends { id: string }>(a: T, b: T) => a.id.localeCompare(b.id);
const sorted = (values: string[]) => [...values].sort((a, b) => a.localeCompare(b));

function upsert(table: string, columns: string[], rows: string[][], key: string[]): string {
  if (rows.length === 0) return '';
  const update = columns.filter((c) => !key.includes(c));
  const conflict = update.length
    ? `do update set ${update.map((c) => `${c} = excluded.${c}`).join(', ')}`
    : 'do nothing';
  return [
    `insert into public.${table} (${columns.join(', ')}) values`,
    rows.map((row) => `  (${row.join(', ')})`).join(',\n'),
    `on conflict (${key.join(', ')}) ${conflict};`,
    '',
  ].join('\n');
}

function nameRows(names: NameMap, ids: string[]): string[][] {
  return ids.flatMap((id) =>
    Object.entries(names[id] ?? {})
      .filter((entry): entry is [string, string] => Boolean(entry[1]))
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([locale, name]) => [lit(id), lit(locale), lit(name)]),
  );
}

/** Keeps exactly `ids` for one regulation: removes rows no longer listed, adds new ones. */
function legalList(table: string, column: string, regulation: string, ids: string[]): string {
  const list = sorted(ids);
  const keep = list.length ? `and ${column} <> all (array[${list.map(lit).join(', ')}]::text[])` : '';
  return [
    `delete from public.${table} where regulation_id = ${lit(regulation)} ${keep};`.replace(/ +;/, ';'),
    upsert(table, ['regulation_id', column], list.map((id) => [lit(regulation), lit(id)]), ['regulation_id', column]),
  ].join('\n');
}

export function referenceSql(data: ReferenceData): string {
  const forms = [...data.forms].sort(byId);
  const items = [...data.items].sort(byId);
  const regulations = [...data.regulations].sort(byId);
  const variants = Object.entries(data.variants)
    .sort(([a], [b]) => a.localeCompare(b))
    .flatMap(([formId, list]) => list.map((variant, position) => ({ ...variant, formId, position })));
  const variantNames: NameMap = Object.fromEntries(variants.map((v) => [v.id, v.names]));

  const parts = [
    '-- Reference data, generated by `npm run seed` from data/. Don\'t edit by hand: change data/,',
    '-- run the seed, and it writes a new migration when anything differs. Safe to apply twice.',
    '',
    upsert('regulations', ['id', 'name', 'starts_at', 'ends_at'],
      regulations.map((r) => [lit(r.id), lit(r.name), lit(r.starts_at), lit(r.ends_at)]), ['id']),
    upsert('forms', ['id', 'species_id', 'dex_number', 'types', 'sprite_key'],
      forms.map((f) => [lit(f.id), lit(f.species_id), lit(f.dex_number), `array[${f.types.map(lit).join(', ')}]`, lit(f.sprite_key)]), ['id']),
    upsert('form_names', ['form_id', 'locale', 'name'], nameRows(data.formNames, forms.map((f) => f.id)), ['form_id', 'locale']),
    upsert('items', ['id', 'category', 'mega_target', 'mega_base_form', 'sprite_key'],
      items.map((i) => [lit(i.id), lit(i.category), lit(i.mega_target), lit(i.mega_base_form), lit(i.sprite_key)]), ['id']),
    upsert('item_names', ['item_id', 'locale', 'name'], nameRows(data.itemNames, items.map((i) => i.id)), ['item_id', 'locale']),
    upsert('form_variants', ['id', 'form_id', 'position'],
      variants.map((v) => [lit(v.id), lit(v.formId), lit(v.position)]), ['id']),
    upsert('variant_names', ['variant_id', 'locale', 'name'], nameRows(variantNames, variants.map((v) => v.id)), ['variant_id', 'locale']),
  ];
  for (const r of regulations) {
    parts.push(
      `-- ${r.id}: legal forms, items and Mega Evolutions. Megas go first and come back last,`,
      '-- since they reference the item list.',
      `delete from public.regulation_megas where regulation_id = ${lit(r.id)};`,
      legalList('regulation_forms', 'form_id', r.id, r.forms),
      legalList('regulation_items', 'item_id', r.id, r.items),
      upsert('regulation_megas', ['regulation_id', 'item_id'], sorted(r.megas).map((id) => [lit(r.id), lit(id)]), ['regulation_id', 'item_id']),
    );
  }
  return parts.filter((part) => part !== '').join('\n');
}

/** The newest reference-data migration, if any. */
export function latestReferenceMigration(dir = MIGRATIONS_DIR): { file: string; sql: string } | null {
  if (!existsSync(dir)) return null;
  const file = readdirSync(dir).filter((f) => f.endsWith(SUFFIX)).sort().at(-1);
  return file ? { file, sql: readFileSync(join(dir, file), 'utf8') } : null;
}

/** Migration versions are UTC timestamps; a new one must sort after every existing migration. */
export function nextMigrationName(existing: string[], now = new Date()): string {
  const stamp = (d: Date) => d.toISOString().replace(/\D/g, '').slice(0, 14);
  const latest = existing.map((f) => f.slice(0, 14)).filter((v) => /^\d{14}$/.test(v)).sort().at(-1);
  let version = stamp(now);
  if (latest && version <= latest) {
    const next = new Date(Date.UTC(+latest.slice(0, 4), +latest.slice(4, 6) - 1, +latest.slice(6, 8),
      +latest.slice(8, 10), +latest.slice(10, 12), +latest.slice(12, 14) + 1));
    version = stamp(next);
  }
  return `${version}${SUFFIX}`;
}
